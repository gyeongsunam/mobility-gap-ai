"""시군구 코드(2026 현행, 2025 이전) → 분석 단위(unit) 코드 변환 규칙 (p01과 동일한 정의)."""
import re

OLD_GWANGJU = {"동구": "29110", "서구": "29140", "남구": "29155", "북구": "29170", "광산구": "29200"}
OLD_JEONNAM = {"목포시": "46110", "여수시": "46130", "순천시": "46150", "나주시": "46170", "광양시": "46230",
               "담양군": "46710", "곡성군": "46720", "구례군": "46730", "고흥군": "46770", "보성군": "46780",
               "화순군": "46790", "장흥군": "46800", "강진군": "46810", "해남군": "46820", "영암군": "46830",
               "무안군": "46840", "함평군": "46860", "영광군": "46870", "장성군": "46880", "완도군": "46890",
               "진도군": "46900", "신안군": "46910"}
# 일반구를 둔 13개 시(코드 앞 4자리)
PARENT4 = {"4111", "4113", "4117", "4119", "4127", "4128", "4146", "4159", "4311", "4413", "5211", "4711", "4812"}


def to_unit(code, name: str = "") -> str:
    code = str(code).split(".")[0].zfill(5)
    if code.startswith("12"):
        last = re.split(r"\s+", str(name).strip())[-1]
        if last in OLD_GWANGJU and ("광주" in str(name) or code in ("12210", "12240", "12270", "12300", "12330")):
            return OLD_GWANGJU[last]
        if last in OLD_JEONNAM:
            return OLD_JEONNAM[last]
        raise KeyError(f"전남광주 코드 매핑 실패: {code} {name}")
    if code in ("28125", "28155", "28110", "28140"):
        return "28110"
    if code in ("28275", "28290", "28260"):
        return "28260"
    if code[:4] in PARENT4:
        return code[:4] + "0"
    return code
